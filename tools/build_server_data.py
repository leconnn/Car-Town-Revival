"""Bundle the game data for the online server functions.

Writes supabase/functions/_shared/catalog/data.ts (gitignored) from the
converted catalog (assets/ea/data/), our tuning (data/tuning.json) and the
list of cars that have art (assets/ea/art/cars.json), so the server rules see
exactly what the game sees. Run before deploying the functions.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REQUIRED = ["consts", "cars", "car_colors", "parts", "part_categories", "items", "lands", "levels",
            "garage_value_tiers", "jobs", "task_mastery_levels", "missions", "mission_steps", "locations", "consumables", "daily_rewards"]


def main() -> int:
    data_dir = ROOT / "assets" / "ea" / "data"
    data = {}
    for name in REQUIRED:
        path = data_dir / f"{name}.json"
        if not path.is_file():
            print(f"error: {path} missing; run tools/convert_catalog.py first", file=sys.stderr)
            return 1
        data[name] = json.loads(path.read_text(encoding="utf-8"))
    tuning = json.loads((ROOT / "data" / "tuning.json").read_text(encoding="utf-8"))
    art = ROOT / "assets" / "ea" / "art" / "cars.json"
    art_ids = []
    if art.is_file():
        # Same rule as GameData: a body layer in every view.
        for k, v in json.loads(art.read_text(encoding="utf-8")).items():
            views = v.get("views", {})
            if all("body" in views.get(n, {}).get("layers", {}) for n in ("front", "rear", "angle")):
                art_ids.append(int(k))
        art_ids.sort()
    out = ROOT / "supabase" / "functions" / "_shared" / "catalog" / "data.ts"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        "// Generated by tools/build_server_data.py. Do not edit or commit.\n"
        f"export const DATA = {json.dumps(data, ensure_ascii=False, separators=(',', ':'))};\n"
        f"export const TUNING = {json.dumps(tuning, separators=(',', ':'))};\n"
        f"export const ART_CAR_IDS: number[] = {json.dumps(art_ids)};\n",
        encoding="utf-8",
    )
    print(f"wrote {out} ({out.stat().st_size // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
